function loadFernfallSurvivalAssets(base = '') {
  return Promise.all(Object.entries(FERNFALL_SURVIVAL_PATHS).map(([key,path]) =>
    new Promise(resolve => {const img = new Image(); img.onload = () => {fernfallSurvival[key] = img;resolve();}; img.onerror = () => {console.warn('Missing Fernfall asset:', path);resolve();}; img.src = base + path;})));
}
function drawSurvivalSprite(ctx,key,x,y,width=40,height=40) {
  const sprite = fernfallSurvival[key]; if (!sprite || !sprite.complete) return false;
  ctx.save();ctx.imageSmoothingEnabled=false;ctx.drawImage(sprite,x,y,width,height);ctx.restore();return true;
}
